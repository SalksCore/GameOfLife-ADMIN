/** Vrai si la valeur est une clé d'icône connue (sinon c'est un texte à afficher tel quel, ex. un compte à rebours). */
export function isGameIcon(name: string): boolean {
  return name in ICONS;
}

function resolve(name: string | null | undefined): ComponentType<IconProps> {
  if (!name) return Circle;
  const direct = ICONS[name];
  if (direct) return direct;
  const cp = name.codePointAt(0);
  if (cp !== undefined && cp > 0x2000) {
    const key = LEGACY[cp.toString(16).toUpperCase()];
    const found = key ? ICONS[key] : undefined;
    if (found) return found;
  }
  return Circle;
}

/** Icône de contenu : la taille suit la taille de police du parent (1em), la couleur celle du texte. */
export function GameIcon({
  name,
  size = '1em',
  weight = 'regular',
}: {
  name: string | null | undefined;
  size?: string | number;
  weight?: IconProps['weight'];
}) {
  const Cmp = resolve(name);
  return <Cmp size={size} weight={weight} aria-hidden focusable="false" />;
}
